import { createHash } from 'node:crypto';

function escapeMarkdown(value) {
  return String(value ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

function escapeHtml(value) {
  return String(value ?? '').replace(/[&<>"]/g, (character) => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
  })[character]);
}

export function functionMapDigest(functionMap, featureTests) {
  return createHash('sha256')
    .update(JSON.stringify({ functionMap, featureTests }))
    .digest('hex');
}

export function mainlineCallMapDigest(callMap) {
  return createHash('sha256')
    .update(JSON.stringify(callMap))
    .digest('hex');
}

function featureRows(functionMap, featureTests) {
  const testsById = new Map(featureTests.features.map((feature) => [feature.id, feature]));
  return functionMap.features.map((feature) => {
    const tests = testsById.get(feature.id);
    return {
      id: feature.id,
      status: feature.status,
      ownerModule: feature.owner_module,
      entrySymbols: feature.entry_symbols.map((entry) => `${entry.path}::${entry.symbol}`),
      ownerResource: tests?.owner_resource || '',
      requiredCommands: tests?.required_commands || [],
      positive: tests?.positive || [],
      negative: tests?.negative || [],
    };
  });
}

export function renderFunctionMapMarkdown(functionMap, featureTests) {
  const digest = functionMapDigest(functionMap, featureTests);
  const rows = featureRows(functionMap, featureTests).map((feature) => [
    `\`${escapeMarkdown(feature.id)}\``,
    escapeMarkdown(feature.status),
    `\`${escapeMarkdown(feature.ownerModule)}\``,
    feature.entrySymbols.map((symbol) => `\`${escapeMarkdown(symbol)}\``).join('<br>'),
    `\`${escapeMarkdown(feature.ownerResource)}\``,
    feature.requiredCommands.map((command) => `\`${escapeMarkdown(command)}\``).join('<br>'),
    feature.positive.map((testPath) => `\`${escapeMarkdown(testPath)}\``).join('<br>'),
    feature.negative.map((testPath) => `\`${escapeMarkdown(testPath)}\``).join('<br>'),
  ].join(' | '));

  return `<!-- generated by v2/docs/wiki/build.mjs; source-sha256=${digest} -->
# v2 Function Map

Machine-generated review surface for \`v2/docs/function_map.json\` joined with
\`v2/docs/feature_tests.json\`. Edit the JSON truth, then rebuild this file.

| feature_id | status | owner_module | entry_symbols | owner_resource | required_commands | positive_tests | negative_tests |
|---|---|---|---|---|---|---|---|
${rows.map((row) => `| ${row} |`).join('\n')}
`;
}

export function renderFunctionMapHtml(functionMap, featureTests) {
  const digest = functionMapDigest(functionMap, featureTests);
  const rows = featureRows(functionMap, featureTests).map((feature) => `
    <tr>
      <td><code>${escapeHtml(feature.id)}</code></td>
      <td>${escapeHtml(feature.status)}</td>
      <td><code>${escapeHtml(feature.ownerModule)}</code></td>
      <td>${feature.entrySymbols.map((symbol) => `<code>${escapeHtml(symbol)}</code>`).join('<br>')}</td>
      <td><code>${escapeHtml(feature.ownerResource)}</code></td>
      <td>${feature.requiredCommands.map((command) => `<code>${escapeHtml(command)}</code>`).join('<br>')}</td>
    </tr>`).join('\n');
  return `<!-- GENERATED:function-map:start source-sha256=${digest} -->
<h2 id="function-map">Function Map</h2>
<table><thead><tr><th>feature_id</th><th>status</th><th>owner</th><th>entry symbols</th><th>resource</th><th>required commands</th></tr></thead>
<tbody>${rows}</tbody></table>
<!-- GENERATED:function-map:end -->`;
}

export function renderMainlineCallMapMarkdown(callMap) {
  const digest = mainlineCallMapDigest(callMap);
  const rows = callMap.edges.map((edge) => [
    `\`${escapeMarkdown(edge.feature_id)}\``,
    `\`${escapeMarkdown(edge.from)}\``,
    `\`${escapeMarkdown(edge.to)}\``,
    `\`${escapeMarkdown(`${edge.caller.path}::${edge.caller.symbol}`)}\``,
    `\`${escapeMarkdown(edge.caller.local_symbol || '')}\``,
    `\`${escapeMarkdown(`${edge.callee.path}::${edge.callee.symbol}`)}\``,
    `\`${escapeMarkdown(edge.callee.local_symbol || '')}\``,
    `\`${escapeMarkdown(JSON.stringify(edge.invocation || { kind: 'direct' }))}\``,
    escapeMarkdown(edge.semantic_io),
  ].join(' | '));
  return `<!-- generated by v2/docs/wiki/build.mjs; source-sha256=${digest} -->
# v2 Mainline Call Map

Machine-generated review surface for \`v2/docs/mainline_call_map.json\`.
Edit the JSON truth, then rebuild this file.

| feature_id | from | to | caller | caller_local | callee | callee_local | invocation | semantic_io |
|---|---|---|---|---|---|---|---|---|
${rows.map((row) => `| ${row} |`).join('\n')}
`;
}

